// Helper to look up an article by ID or Title across all sections
export function findArticle(idOrTitle: string): NewsArticle | undefined {
  const allArticles: NewsArticle[] = [
    leadStory,
    ...sideLeadNews,
    ...gridSectionTwoCards,
    nationalNewsMain,
    ...nationalNewsList,
    politicsFeatured,
    ...politicsList,
    ...internationalNews,
    economyNews.featured,
    lawNews.featured,
    entertainmentNews.featured,
    ...mediaNewsGrid,
    ...sportsList,
    techNews.featured,
    educationNews.featured,
    opinionNews.featured,
    ...latestNewsTab,
    ...popularNewsTab,
  ];

  return allArticles.find(
    (a) => String(a.id) === String(idOrTitle) || a.title === idOrTitle
  );
}

